(ns generics.AnonymousSubclassConstruction
  (:gen-class)
  (:require [generics.GenericSupport :as gs])
  (:import [org.mases.jcobridge.netreflection JCOReflector]
           [system Console Environment]
           [system.collections.generic List_1]))

;; Baseline: a reflected generic class can be constructed as an anonymous-like subclass,
;; here generated by generics.GenericSupport because Clojure cannot write `new List_1<T>() {}`.
(defn- test-anonymous-subclass-construction []
  (let [lst (gs/new-generic List_1 [system.Object])]
    (when (nil? lst)
      (throw (AssertionError. "Expected a non-null List_1 instance")))))

(defn -main [& args]
  (JCOReflector/setCommandLineArgs (into-array String args))
  (try
    (test-anonymous-subclass-construction)
    (Console/WriteLine "Exiting with success")
    (Environment/Exit 0)
    (catch Throwable tre
      (.printStackTrace tre)
      (System/exit -1))))
